import 'package:flutter/foundation.dart';
import 'package:sholovvo_app/features/feed/domain/entities/post.dart';
import 'package:sholovvo_app/features/feed/domain/post_image_storage.dart';

/// Who a post is attributed to, captured before publish is tapped.
///
/// A snapshot, for the reason [Post] documents: the document repeats the name
/// and photo that were current at that moment, so a later rename does not
/// rewrite history and the feed does not spend one profile read per card.
///
/// **The uid is deliberately not here.** The repository takes it from the
/// session, which is the value `firestore.rules` compares `authorUid` against.
/// A draft that carried a uid would be a form that could claim to belong to
/// somebody else, and the lie would only be refused by the server after a wasted
/// write. Not carrying it makes the honest write the only writable one.
@immutable
final class PostAuthor {
  const PostAuthor({required this.name, this.photoUrl});

  /// No profile has been read yet.
  ///
  /// Not an error: a donor who never filled their profile still posts. The
  /// document then holds an empty name, which the feed renders as the person
  /// icon rather than as an invented initial.
  const PostAuthor.unknown() : name = '', photoUrl = null;

  /// The display name to write into the document. May be empty.
  final String name;

  /// The avatar URL to write into the document, if there was one.
  final String? photoUrl;

  @override
  String toString() => 'PostAuthor($name)';
}

/// What a donor is about to publish, before it is a document.
///
/// The compose form's output and the repository's input, with no SDK type and no
/// document id: the id is generated by the write, so inventing one here would be
/// a value the caller could get wrong. The text arrives already trimmed — the
/// form is the last place that knows which whitespace the donor meant.
@immutable
final class PostDraft {
  PostDraft({
    required this.author,
    required this.text,
    List<StoredPostImage> images = const <StoredPostImage>[],
  }) : images = List<StoredPostImage>.unmodifiable(images);

  final PostAuthor author;

  /// What was written, without the leading and trailing whitespace the form
  /// stripped.
  final String text;

  /// Up to [PostValidator.maxImages] stored photographs, in the order they will
  /// appear on the card.
  final List<StoredPostImage> images;

  /// The published URLs, in order.
  List<String> get imageUrls => <String>[
    for (final StoredPostImage image in images) image.url,
  ];

  /// The storage paths behind them, in the same order.
  List<String> get imagePaths => <String>[
    for (final StoredPostImage image in images) image.path,
  ];

  /// What still has to be fixed, or `null` when this can be published.
  ///
  /// The counters are passed as zeros because a new post has no likes and no
  /// comments yet; they are part of the same rule set so that a draft and a
  /// document cannot disagree about what a valid post is.
  PostIssue? get issue => PostValidator.validate(
    text: text,
    imageCount: images.length,
    imagePathCount: images.length,
    likeCount: 0,
    commentCount: 0,
  );

  bool get isPublishable => issue == null;

  @override
  String toString() =>
      'PostDraft(${text.length} chars, ${images.length} images)';
}
