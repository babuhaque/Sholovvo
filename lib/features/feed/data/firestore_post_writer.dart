import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:sholovvo_app/core/error/failure.dart';
import 'package:sholovvo_app/core/error/firestore_error_mapper.dart';
import 'package:sholovvo_app/core/result/result.dart';
import 'package:sholovvo_app/features/feed/data/models/post_document.dart';
import 'package:sholovvo_app/features/feed/data/post_writer.dart';

/// Writes the `posts` collection, one document at a time.
///
/// No validation and no mapping: the repository has already refused an
/// unpublishable draft and built the fields, so this class is deliberately
/// nothing but the session, the call, and its error translation.
///
/// **`set` on a pre-allocated id, not `add`.** The id arrives from [newPostId]
/// so the repository can return a fully-formed post; `add` would hand the id
/// back only after the write. Both are a single write, and an id generated by
/// the client is the same kind of id the server would generate.
class FirestorePostWriter implements PostWriter {
  FirestorePostWriter(this._auth, this._firestore);

  final FirebaseAuth _auth;
  final FirebaseFirestore _firestore;

  CollectionReference<Map<String, dynamic>> get _posts =>
      _firestore.collection(PostDocument.collection);

  @override
  String? get authorUid => _auth.currentUser?.uid;

  @override
  String newPostId() => _posts.doc().id;

  @override
  Future<Result<void>> createPost(String id, Map<String, Object?> fields) async {
    try {
      await _posts.doc(id).set(fields);
      return const Success<void>(null);
    } on FirebaseException catch (error, stackTrace) {
      return FailureResult<void>(
        mapFirestoreCodeToFailure(
          error.code,
          debugMessage: error.message,
          cause: error,
          stackTrace: stackTrace,
        ),
      );
    } catch (error, stackTrace) {
      return FailureResult<void>(mapExceptionToFailure(error, stackTrace));
    }
  }
}
